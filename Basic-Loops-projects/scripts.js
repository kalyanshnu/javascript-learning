// 4) Factorial Calculator
// Challenge: Take a positive integer and calculate its factorial.
// Example:
// Input: 5
// Output: 120
// Explanation:
// 5! = 5 × 4 × 3 × 2 × 1
// Requirements:
// Solve using a for loop.
// Solve again using a while loop.
// Handle 0! = 1.
// Bonus: Reject negative numbers.


