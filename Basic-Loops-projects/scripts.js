// Print tables from 1 to 10.


// 3) Sum & Average Calculator
// Challenge: Calculate the sum and average of numbers.
// Requirements:
// Ask the user how many numbers they want to enter.
// Use a loop to take those numbers.
// Calculate the total sum.
// Calculate the average.
// Example:
// Input: 5 numbers
// 10, 20, 30, 40, 50
// Sum: 150
